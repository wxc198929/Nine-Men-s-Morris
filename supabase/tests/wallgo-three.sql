begin;
do $test$
declare ids uuid[]:=array[gen_random_uuid(),gen_random_uuid(),gen_random_uuid(),gen_random_uuid()]; rid uuid; r public.wallgo_rooms; state jsonb:='{"version":2,"players":3,"player":1,"phase":"play","winner":null,"winners":[],"draw":false,"breaks":[1,1,1],"eliminated":[]}'::jsonb; i integer; denied boolean; ratings integer[]; expected integer[];
begin
  for i in 1..4 loop
    insert into auth.users(id,aud,role,email) values(ids[i],'authenticated','authenticated','transaction-test-'||ids[i]||'@example.invalid');
    perform public.wallgo_ensure_profile(ids[i],'事务测试');
  end loop;
  rid:=public.wallgo_create(ids[1],state);
  perform public.wallgo_join(ids[2],(select code from public.wallgo_rooms where id=rid));
  select * into r from public.wallgo_rooms where id=rid;
  assert r.status='waiting' and r.capacity=3 and r.revision=1,'three-player room started before full';
  perform public.wallgo_join(ids[2],r.code);
  assert (select revision from public.wallgo_rooms where id=rid)=1,'duplicate join changed revision';
  perform public.wallgo_join(ids[3],r.code);
  select * into r from public.wallgo_rooms where id=rid;
  assert r.status='playing' and r.green_id=ids[3] and r.revision=2,'third player not seated';
  denied:=false;begin perform public.wallgo_join(ids[4],r.code);exception when others then denied:=true;end;assert denied,'fourth player joined';
  assert public.wallgo_create(ids[3],state)=rid,'green participant escaped active-room limit';
  denied:=false;begin perform public.wallgo_commit(ids[4],rid,2,state,'move');exception when others then denied:=true;end;assert denied,'outsider wrote room';
  denied:=false;begin perform public.wallgo_commit(ids[2],rid,2,state,'move');exception when others then denied:=true;end;assert denied,'wrong side moved';
  denied:=false;begin perform public.wallgo_commit(ids[1],rid,1,state,'move');exception when others then denied:=true;end;assert denied,'stale revision accepted';
  perform public.wallgo_commit(ids[1],rid,2,state||'{"winner":1,"winners":[1],"draw":false}'::jsonb,'move');
  select * into r from public.wallgo_rooms where id=rid;
  assert r.rating_deltas='[16,-8,-8]'::jsonb and r.status='finished','three-player Elo mismatch';
  assert (select wins from public.wallgo_profiles where user_id=ids[1])=1,'win missing';
  assert (select losses from public.wallgo_profiles where user_id=ids[3])=1,'green loss missing';
  denied:=false;begin perform public.wallgo_commit(ids[1],rid,3,state||'{"winner":1,"winners":[1],"draw":false}'::jsonb,'move');exception when others then denied:=true;end;assert denied,'finished room settled twice';
  assert (select wins from public.wallgo_profiles where user_id=ids[1])=1,'double stats';
  update public.wallgo_profiles set rating=1200,wins=0,losses=0,draws=0 where user_id=any(ids);
  rid:=public.wallgo_create(ids[1],state);
  perform public.wallgo_join(ids[2],(select code from public.wallgo_rooms where id=rid));
  perform public.wallgo_join(ids[3],(select code from public.wallgo_rooms where id=rid));
  perform public.wallgo_commit(ids[1],rid,2,state||'{"winner":null,"winners":[1,2],"draw":true}'::jsonb,'move');
  assert (select rating_deltas from public.wallgo_rooms where id=rid)='[8,8,-16]'::jsonb,'tied winners Elo mismatch';
  assert (select draws from public.wallgo_profiles where user_id=ids[1])=1,'first tied winner not draw';
  assert (select draws from public.wallgo_profiles where user_id=ids[2])=1,'second tied winner not draw';
  assert (select losses from public.wallgo_profiles where user_id=ids[3])=1,'third loser incorrectly drew';
  update public.wallgo_profiles set rating=1200,wins=0,losses=0,draws=0 where user_id=any(ids);
  rid:=public.wallgo_create(ids[1],state||'{"players":2}'::jsonb);
  perform public.wallgo_join(ids[2],(select code from public.wallgo_rooms where id=rid));
  assert (select status from public.wallgo_rooms where id=rid)='playing','two-player regression';
  perform public.wallgo_commit(ids[1],rid,1,state||'{"players":2,"winner":2,"winners":[2],"draw":false}'::jsonb,'move');
  assert (select rating_deltas from public.wallgo_rooms where id=rid)='[-16,16]'::jsonb,'two-player Elo regression';
  assert not has_table_privilege('anon','public.wallgo_rooms','SELECT'),'anon can read rooms';
  assert not has_function_privilege('authenticated','public.wallgo_commit(uuid,uuid,integer,jsonb,text)','EXECUTE'),'clients can forge states via RPC';
end;
$test$;
rollback;
select 'passed: full-room gating, green membership, duplicate joins, outsider/wrong-turn/stale rejection, once-only settlement, 3-player Elo, tied winners, 2-player regression, access control; all test rows rolled back' as verification;
